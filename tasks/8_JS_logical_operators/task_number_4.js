// Что выведет код ?

// ```JavaScript
//     if (-1 || 0) console.log( 'один' );
//     if (-1 && 0) console.log( 'два' );
//     if (null || -1 && 1) console.log( 'три' );
// ```


// Solution
if (-1 || 0) console.log('один'); // "один" (|| найдет первым truthy значение -1)
if (-1 && 0) console.log('два'); // консоль лог не сработает, в условии будет false
if (null || -1 && 1) console.log('три'); // "три" (&& сработает первым будет 1 и после || сработает на первом truthy значении 1);