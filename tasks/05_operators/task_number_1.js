// **1 задача:**

// Чему будут равны переменные `a`, `b`, `c` и `d` ?

// ```JavaScript
// let a = 10, b = 10;

// const c = ++a; // ?
// const d = b++; // ?


// Solution
let a = 10, b = 10;

const c = ++a; 
const d = b++;

console.log(a); // 11
console.log(b); // 11
console.log(c); // 11
console.log(d); // 10