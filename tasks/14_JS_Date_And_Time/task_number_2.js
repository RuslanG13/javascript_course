// Отобразите числом сколько лет прошло на сегодняшний день исходя из полученного таймстампа 
// (количества миллисекунд прошедших с 1 января 1970 года) на день решения данной задачи

// ```JavaScript
//     const years = ??;

//     console.log(years); // 54 в 2024 году
// ```


// Solution
const years = Math.floor(Date.now() / 1000 / 60 / 60 / 24 / 365);
console.log(years); // 56 в 2026 году